const storeSkin = ({
  id, name, weapon, theme, color, description, price, inspiration,
  slogan = null, markAsset = null, rightsStatus = 'original-safe', metalFinish = null,
  preserveBase = false, markLayout = null, sloganLayout = null, sloganAspect = null, series = null,
}) => Object.freeze({
  id,
  name,
  status: 'store-active',
  approved: true,
  certified: true,
  runtimeEnabled: true,
  targetWeapons: Object.freeze([weapon]),
  designOrigin: 'project-owned',
  inspiration,
  rightsStatus,
  officialMarksIncluded: false,
  theme,
  slogan,
  ...(markAsset ? { markPlacement: 'receiver-inlay', markAsset } : {}),
  ...(slogan ? { sloganPlacement: 'barrel-horizontal' } : {}),
  ...(metalFinish ? { metalFinish } : {}),
  ...(preserveBase ? { preserveBase: true } : {}),
  ...(markLayout ? { markLayout: Object.freeze(markLayout) } : {}),
  ...(sloganLayout ? { sloganLayout: Object.freeze(sloganLayout) } : {}),
  ...(sloganAspect ? { sloganAspect } : {}),
  storeEnabled: true,
  storePrice: price,
  storeSlot: 'weapon',
  storeWeapon: weapon,
  storeSeries: series || (theme === 'ouro' || theme === 'prata' ? 'METAIS DA TRETA' : 'POLÍTICA NA MIRA'),
  storeColor: color,
  storeDescription: description,
  storePoster: `/img/weapon-skins/${id}.webp`,
});

