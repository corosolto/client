const storeSkin = ({
  id, name, weapon, theme, color, description, price, inspiration,
  slogan = null, markAsset = null, rightsStatus = 'original-safe', metalFinish = null,
}) => Object.freeze({
  id,
  name,
  status: 'store-active',
  approved: true,
  certified: true,
  runtimeEnabled: true,
  targetWeapons: Object.freeze([weapon]),
  designOrigin: 'project-owned',
  inspiration,
  rightsStatus,
  officialMarksIncluded: false,
  theme,
  slogan,
  ...(markAsset ? { markPlacement: 'receiver-inlay', markAsset } : {}),
  ...(slogan ? { sloganPlacement: 'barrel-horizontal' } : {}),
  ...(metalFinish ? { metalFinish } : {}),
  storeEnabled: true,
  storePrice: price,
  storeSlot: 'weapon',
  storeWeapon: weapon,
  storeSeries: theme === 'ouro' || theme === 'prata' ? 'METAIS DA TRETA' : 'POLÍTICA NA MIRA',
  storeColor: color,
  storeDescription: description,
  storePoster: `/img/weapon-skins/${id}.webp`,
});

