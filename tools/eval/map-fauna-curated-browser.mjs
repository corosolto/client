// Reusa somente a TaskSpace informada; requer o guia atual do ego-browser lido pelo operador.
import fs from 'node:fs';
import path from 'node:path';
import { parseArgs } from 'node:util';
import { spawnSync } from 'node:child_process';
import { auditCuratedFauna } from './map-fauna-curated.mjs';
const {values}=parseArgs({options:{space:{type:'string'},fotos:{type:'string',default:'2'},out:{type:'string'},base:{type:'string',default:'http://127.0.0.1:8545'},page:{type:'string',default:'p2'}}});
if(!/^\d+$/.test(values.space||'')||!values.out||!path.isAbsolute(values.out))throw Error('Informe --space ID da própria tarefa e --out /caminho/absoluto. Leia ego-browser skill antes.');
const fotos=Number(values.fotos);if(!Number.isSafeInteger(fotos)||fotos<0)throw Error('--fotos deve ser inteiro não negativo.');
const base=new URL(values.base);if(!['http:','https:'].includes(base.protocol))throw Error('Base HTTP(S) obrigatória.');
fs.mkdirSync(values.out,{recursive:true});
const config={space:Number(values.space),dir:values.out,base:base.href.replace(/\/$/,''),pageId:values.page,fotos};
const source=fs.readFileSync(new URL('./map-fauna-curated-capture.mjs',import.meta.url),'utf8');
const script='const FAUNA_CAPTURE_CONFIG='+JSON.stringify(config)+';\n'+source;
const result=spawnSync('ego-browser',['nodejs'],{input:script,encoding:'utf8',maxBuffer:2*1024*1024,timeout:120000});
fs.writeFileSync(path.join(values.out,'map-fauna-capture.log'),(result.stdout||'')+(result.stderr||''));
if(result.error||result.status!==0)throw Error('Captura Ego falhou; veja map-fauna-capture.log. '+(result.error?.message||'exit '+result.status));
const data=JSON.parse(fs.readFileSync(path.join(values.out,'map-fauna-curated-runtime.json'),'utf8'));
const refs=JSON.parse(fs.readFileSync(new URL('./map-fauna-curated.json',import.meta.url),'utf8'));
const reports=data.results.map(sample=>auditCuratedFauna(sample,refs));
if(data.results.length!==new Set(refs.map(r=>r.map)).size)throw Error('Censo incompleto dos mapas curados.');
fs.writeFileSync(path.join(values.out,'map-fauna-audit.json'),JSON.stringify({utc:new Date().toISOString(),scope:'mapview GLBs, textures, deterministic controller/mixer; screenshots require independent visual review; actual mobile match separate',reports},null,2)+'\n');
console.log(JSON.stringify(reports));if(reports.some(r=>!r.pass))process.exitCode=1;
